#!/usr/bin/env node
/*
 * scripts/setup.mjs - print ready-to-paste MCP client configuration for THIS
 * machine.
 *
 * The repository never stores an absolute path. This script detects the two
 * values that genuinely differ between computers (the node binary and the
 * location of src/server.mjs) and renders them into every example.
 *
 * Usage:
 *   node scripts/setup.mjs                  human readable report (default)
 *   node scripts/setup.mjs --dsh            only the DSH cordis.patch.yml block
 *   node scripts/setup.mjs --json           machine readable JSON
 *   node scripts/setup.mjs --out <file>     write the DSH block to <file>
 *   node scripts/setup.mjs --check          probe Zotero and exit 0/1
 *   node scripts/setup.mjs --help
 */

import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  SERVER_NAME,
  readVersion,
  resolveApiBase,
  resolveTimeoutMs,
  stdioServerConfig,
} from "../src/config.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SERVER_ENTRY = path.resolve(HERE, "..", "src", "server.mjs");
const NODE_EXECUTABLE = process.execPath;
const VERSION = readVersion();
const API_BASE = resolveApiBase();
const TIMEOUT_MS = resolveTimeoutMs();
const PROBE_TIMEOUT_MS = 2500;

/* --------------------------------------------------------------- helpers */

function fail(message) {
  process.stderr.write("setup: " + message + "\n");
  process.exitCode = 1;
}

/** YAML single-quoted scalar: backslashes stay literal, ' is doubled. */
function yamlQuote(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function dshPatch() {
  return [
    "# --- Zotero MCP bridge (generated by scripts/setup.mjs) ---",
    "# Zotero must be running with:",
    "#   Edit > Settings > Advanced >",
    "#   \"Allow other applications on this computer to communicate with Zotero\"",
    "# Tools surface to the model as mcp__zotero__<tool>.",
    "#",
    "# Server file: " + SERVER_ENTRY,
    "# (editing this entry makes dsh-mcp-client reconnect and restart the server)",
    "- insert:",
    "    - id: mcp-zotero",
    "      name: '@deepseek-ai/dsh-mcp-client'",
    "      config:",
    "        serverName: zotero",
    "        transport: stdio",
    "        command: " + yamlQuote(NODE_EXECUTABLE),
    "        args:",
    "          - " + yamlQuote(SERVER_ENTRY),
    "        env:",
    "          ZOTERO_API_BASE: " + yamlQuote(API_BASE),
    "        toolCallTimeoutMs: " + (TIMEOUT_MS > 90000 ? TIMEOUT_MS : 90000),
    "        failOnStartupError: false",
    "",
  ].join("\n");
}

function genericConfig() {
  const config = {};
  config.zotero = stdioServerConfig({
    nodePath: NODE_EXECUTABLE,
    serverPath: SERVER_ENTRY,
    env: { ZOTERO_API_BASE: API_BASE },
  });
  return { mcpServers: config };
}

/** Look for DSH profile directories that already carry a patch layer. */
function detectDshProfiles() {
  const root = path.join(homedir(), ".dsh", "profiles");
  if (!existsSync(root)) return [];
  let names;
  try {
    names = readdirSync(root);
  } catch (err) {
    return [];
  }
  const found = [];
  for (const name of names) {
    const dir = path.join(root, name);
    try {
      if (!statSync(dir).isDirectory()) continue;
    } catch (err) {
      continue;
    }
    found.push({
      name: name,
      dir: dir,
      patchFile: path.join(dir, "cordis.patch.yml"),
      hasPatchFile: existsSync(path.join(dir, "cordis.patch.yml")),
    });
  }
  return found.sort(function (a, b) { return a.name.localeCompare(b.name); });
}

/** Ask Zotero's local API whether it is awake. Never throws. */
async function probe() {
  const url = API_BASE.replace(/\/+$/, "") + "/items/top?limit=1";
  const result = { url: url, reachable: false };
  const controller = new AbortController();
  const timer = setTimeout(function () { controller.abort(); }, PROBE_TIMEOUT_MS);
  try {
    const response = await fetch(url, {
      headers: { "Zotero-API-Version": "3", "Accept": "application/json" },
      signal: controller.signal,
    });
    result.status = response.status;
    if (response.ok) {
      const body = await response.json().catch(function () { return null; });
      result.reachable = true;
      result.sampleSize = Array.isArray(body) ? body.length : 0;
    } else {
      result.error = "HTTP " + response.status + " " + response.statusText;
    }
  } catch (err) {
    result.error = err && err.name === "AbortError"
      ? "timed out after " + PROBE_TIMEOUT_MS + " ms"
      : (err && err.message ? err.message : String(err));
  } finally {
    clearTimeout(timer);
  }
  return result;
}

/* ------------------------------------------------------------------- cli */

function usage() {
  return [
    SERVER_NAME + " setup " + VERSION,
    "",
    "Prints MCP client configuration for this machine.",
    "",
    "Usage: node scripts/setup.mjs [options]",
    "",
    "  (no options)      Human readable report with every snippet.",
    "  --dsh             Print only the DSH cordis.patch.yml block.",
    "  --json            Print a machine readable JSON report.",
    "  --out <file>      Write the DSH block to <file> (creates directories).",
    "  --check           Probe Zotero; exit 0 when reachable, 1 otherwise.",
    "  -h, --help        Show this help.",
    "",
  ].join("\n");
}

function humanReport(zotero, profiles) {
  const lines = [];
  lines.push(SERVER_NAME + " setup " + VERSION);
  lines.push("=".repeat(SERVER_NAME.length + 13));
  lines.push("");
  lines.push("Detected on this machine");
  lines.push("  server entry   " + SERVER_ENTRY);
  lines.push("  node           " + NODE_EXECUTABLE);
  lines.push("  api base       " + API_BASE);
  lines.push("  timeout        " + TIMEOUT_MS + " ms");
  if (!profiles.length) {
    lines.push("  DSH profiles   none found under " + path.join(homedir(), ".dsh", "profiles"));
  } else {
    for (const profile of profiles) {
      lines.push("  DSH profile    " + profile.dir + (profile.hasPatchFile ? "  (cordis.patch.yml present)" : "  (no cordis.patch.yml yet)"));
    }
  }
  lines.push("  Zotero         " + (zotero.reachable
    ? "reachable (" + (zotero.sampleSize === undefined ? "?" : zotero.sampleSize) + " item(s) sampled)"
    : "NOT reachable - " + (zotero.error || "unknown error")));
  lines.push("");
  lines.push("1. DeepSeek Harness (DSH)");
  lines.push("   Append this block to a profile patch layer, then restart DSH:");
  lines.push("");
  for (const line of dshPatch().split("\n")) lines.push("   " + line);
  lines.push("");
  lines.push("2. Any other MCP client");
  lines.push("   Full path: " + SERVER_ENTRY);
  lines.push("");
  for (const line of JSON.stringify(genericConfig(), null, 2).split("\n")) lines.push("   " + line);
  lines.push("");
  lines.push("3. Verify");
  lines.push("   node " + path.relative(process.cwd(), SERVER_ENTRY) + " --check");
  lines.push("");
  return lines.join("\n");
}

async function main(argv) {
  const args = argv.slice();
  if (args.indexOf("-h") !== -1 || args.indexOf("--help") !== -1) {
    process.stdout.write(usage());
    return 0;
  }

  const asJson = args.indexOf("--json") !== -1;
  const dshOnly = args.indexOf("--dsh") !== -1;
  const outIndex = args.indexOf("--out");
  const outFile = outIndex >= 0 ? args[outIndex + 1] : null;
  if (outIndex >= 0 && !outFile) {
    fail("--out needs a file path.");
    return 1;
  }

  const zotero = await probe();
  const profiles = detectDshProfiles();

  if (args.indexOf("--check") !== -1) {
    process.stdout.write("zotero-harness-bridge setup --check\n");
    process.stdout.write("  api base   " + API_BASE + "\n");
    process.stdout.write("  reachable  " + (zotero.reachable ? "yes" : "NO") + "\n");
    if (zotero.error) process.stdout.write("  error      " + zotero.error + "\n");
    return zotero.reachable ? 0 : 1;
  }

  if (outFile) {
    const target = path.resolve(outFile);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, dshPatch(), "utf8");
    process.stdout.write("Wrote the DSH patch block to " + target + "\n");
    return 0;
  }

  if (dshOnly) {
    process.stdout.write(dshPatch());
    return 0;
  }

  if (asJson) {
    process.stdout.write(JSON.stringify({
      server: SERVER_NAME,
      version: VERSION,
      node: NODE_EXECUTABLE,
      serverEntry: SERVER_ENTRY,
      apiBase: API_BASE,
      timeoutMs: TIMEOUT_MS,
      zotero: zotero,
      dshProfiles: profiles,
      configs: {
        dsh: dshPatch(),
        generic: genericConfig(),
      },
    }, null, 2) + "\n");
    return 0;
  }

  process.stdout.write(humanReport(zotero, profiles) + "\n");
  return 0;
}

main(process.argv.slice(2)).then(function (code) {
  process.exitCode = code;
}, function (err) {
  fail(err && err.stack ? err.stack : String(err));
});
